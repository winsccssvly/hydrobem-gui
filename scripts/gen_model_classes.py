"""Writes python/hydrobem_gui/_classes.py from the schema of the engine: per object type
of the model a class with a property per item and per list of children, its docstring the
description, unit, default and choices of the schema, and an ``update`` with a keyword per item and
list; per object type held in a list, the class of the list with an ``add`` with a keyword per item
and list (each described in its Args); and ModelLists, the typed objects and lists of hb.Model.
HydroBEM's script also writes the tree of the inputs into its docs/reference/inputs.md; this
repository has no such document, so only the classes are written (``doc_tree`` gives the tree).

    python scripts/gen_model_classes.py            # writes the file
    python scripts/gen_model_classes.py --check    # exit 1 when the file is not up to date

hydrobem.dll must be loadable (engine/ imported, or HYDROBEM_DLL): the schema is read through
hydrobem_gui._core.
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "python" / "hydrobem_gui" / "_classes.py"
DOC = ROOT / "docs" / "reference" / "inputs.md"
BEGIN = "<!-- input tree: generated by scripts/gen_model_classes.py, do not edit -->"
END = "<!-- end of the input tree -->"
sys.path.insert(0, str(ROOT / "python"))

ARRAY_TEXT = "text"  # the element type of a text array in the schema


def _type(d: dict) -> tuple[str, str]:
    """The annotation of the value read and of the value set."""
    k, unset = d["kind"], d["default"] is None
    opt = " | None" if unset else ""
    if k == "bool":
        return "bool", "bool"
    if k in ("int", "real"):
        t = "int" if k == "int" else "float"
        if d["choices"]:  # a number or one of its names
            t += " | Literal[" + ", ".join(repr(c) for c in d["choices"]) + "]"
        return t + opt, t + opt
    if k == "choice":
        lit = "Literal[" + ", ".join(repr(c) for c in d["choices"]) + "]"
        return lit + opt, lit + opt
    if k in ("text", "selection", "reference"):
        return "str" + opt, "str" + opt
    if k == "origin":
        return "str | np.ndarray", "str | ArrayLike"
    if k == "array" and d["dtype"] == ARRAY_TEXT:
        return "tuple[str, ...]" + opt, "Sequence[str]" + opt
    return "np.ndarray" + opt, "ArrayLike" + opt  # array, terms


def _default(d: dict) -> str:
    v = d["default"]
    if v is None:
        return "unset"
    if v in ('""', "[]"):
        return "empty"
    return v.replace('"', "")


def _doc(text: str, indent: int) -> str:
    lines = []
    for para in text.split("\n\n"):
        lines += textwrap.wrap(para, 116 - indent) or [""]
        lines.append("")
    pad = " " * indent
    body = "\n".join((pad + x) if x else "" for x in lines[:-1]).lstrip()
    return f'{pad}"""{body}"""'


def _used_with(d: dict) -> str:
    """The switch values that take a switched item, e.g. 'control_surface = "cylinder", or
    control_surface = "automatic" with control_surface_outer = "circle"'."""
    out = []
    for t in d["switch_values"]:
        out.append(" with ".join(f'{sw} = "{v}"' for sw, v in zip(d["switch"], t.split("/"), strict=False)))
    return ", or ".join(out)


def _facts(d: dict) -> str:
    facts = []
    if d["unit"]:
        facts.append(f"Unit: {d['unit']}.")
    facts.append(f"Default: {_default(d)}.")
    if d["kind"] == "choice":
        facts.append("Choices: " + ", ".join(d["choices"]) + ".")
    elif d["choices"] and d["kind"] == "array":
        facts.append("Each one of: " + ", ".join(d["choices"]) + ".")
    elif d["choices"]:
        facts.append("Or one of: " + ", ".join(d["choices"]) + ".")
    if d["kind"] == "reference":
        facts.append(f"The name of an object of {d['target']}.")
    elif d["target"] and d["kind"] == "array":
        facts.append(f"Each the names of an object of {d['target']}, separated by '/'.")
    if d["switch"]:
        facts.append("Used with " + _used_with(d) + "; kept unused otherwise.")
    if d["kinds"]:
        facts.append("Meshes of the kinds " + ", ".join(d["kinds"]) + ".")
    return " ".join(facts)


def _item(name: str, d: dict) -> str:
    get, put = _type(d)
    doc = _doc(d["description"] + "\n\n" + _facts(d), 8)
    setter = f"    def {name}(self, value: {put}) -> None:"
    if len(setter) > 120:  # the line length of the project (ruff)
        setter = f"    def {name}(\n        self, value: {put}\n    ) -> None:"
    getter = f"    def {name}(self) -> {get}:"
    if len(getter) > 120:
        getter = f"    def {name}(\n        self,\n    ) -> {get}:"
    return f'''
    @property
{getter}
{doc}
        return self._o.get("{name}")

    @{name}.setter
{setter}
        self._set("{name}", value)
'''


def _list(name: str, d: dict) -> str:
    kinds = " or ".join(d["types"])
    # the single objects (environment, options, ...) are the model's own attributes (engine.py)
    assert not d["single"], name
    named = _indexed("named" if d["named"] else "optional" if d["optional_names"] else "")
    doc = _doc(f"{d['description']}\n\nA list of {kinds} objects, indexed {named}; its objects are made by "
               "add() and insert(), once this object is made (it is not assigned; clear() empties it).", 8)
    return f'''
    @property
    def {name}(self) -> {_list_type(d)}:
{doc}
        return self._child("{name}")
'''


def _indexed(names: str) -> str:
    """How the objects of a list are found: "named" (every object has a name), "optional" (an
    object may have one) or "" (none)."""
    return {"named": "by name and by position", "optional": "by position or by name"}.get(
        names, "by position")


def _typed_dict(t: str, v: dict, multi: bool, named: bool) -> str:
    """``<Type>Items``: the own items of an object type as the keys of a dict, for the dicts of
    add() and update() keywords; every key optional (the engine checks what is required), every
    item also None, and "name" for the objects of a list with names."""
    lines = [f"\n\nclass {t}Items(TypedDict, total=False):",
             _doc(f"The items of {'an' if t[0] in 'AEIOU' else 'a'} {t} as the keys of a dict (a child set from "
                  "a dict).", 4)]
    if multi:
        lines.append(f'    type: Literal["{t}"]')
    if named and "name" not in v["items"]:
        lines.append("    name: str")
    for n, d in v["items"].items():
        a = _type(d)[1]
        lines.append(f"    {n}: {a if n == 'name' or a.endswith('| None') else a + ' | None'}")
    return "\n".join(lines) + "\n"


def _list_type(d: dict) -> str:
    """The annotation of a list of children: the class of the list (one type) or ObjectList."""
    return f"{d['types'][0]}List" if len(d["types"]) == 1 else "ObjectList[ModelObject]"


def _keywords(v: dict, name: str | None = None) -> tuple[list[str], list[str]]:
    """The keywords of a generated ``add`` or ``update``: a parameter per own item (the default
    ``...``: not given; the objects of a list are added to it), and their Args, the
    description of each. The item ``name`` of the
    objects of a named list is the first argument of ``add`` (``name``: its Args line) and is
    changed by ``rename``, not by ``update``."""
    params, args = [], []
    if name is not None:
        args.append(("name", name))
    for n, d in v["items"].items():
        if n == "name":
            continue
        assert n not in ("self", "type"), n
        params.append(f"{n}: {_type(d)[1]} = ...")
        args.append((n, d["description"] + " " + _facts(d)))
    lines = []
    for n, text in args:
        wrapped = textwrap.wrap(f"{n}: {text}", 104)
        lines.append("            " + wrapped[0])
        lines += ["                " + x for x in wrapped[1:]]
    return params, lines


def _signature(head: str, params: list[str], returns: str) -> str:
    """``def head*, p1, p2, ...) -> returns:``, wrapped at 120 columns."""
    out, line = [], f"    def {head}*,"
    for i, p in enumerate(params):
        end = f") -> {returns}:" if i == len(params) - 1 else ","
        if len(line) + 1 + len(p) + len(end) > 120:
            out.append(line)
            line = "           "
        line += " " + p + end
    out.append(line)
    return "\n".join(out)


def _update(v: dict) -> str:
    params, args = _keywords(v)
    if not params:
        return ""
    return f'''
{_signature("update(self, ", params, "None")}
        """Sets the items given (and replaces the lists given); the others stay as they are. None
        returns an item to its default.

        Args:
{chr(10).join(args)}
        """
        self._update(locals())
'''


def _list_class(t: str, v: dict, names: str) -> str:
    """The class of a list of objects of type t; names "named", "optional" or "" (_indexed)."""
    name = v["items"]["name"]["description"] if "name" in v["items"] else f"The name of the {t} in the list."
    if names == "optional":
        name = f"The name of the {t} in the list, unique within it; None: none (found by its position)."
    params, args = _keywords(v, name if names else None)
    base = "MeshListBase" if t == "Mesh" else f"ObjectList[{t}]"
    heads = {"named": "add(self, name: str, ", "optional": "add(self, name: str | None = None, "}
    head = heads.get(names, "add(self, ")
    indexed = _indexed(names)
    named = bool(names)
    return f'''

class {t}List({base}):
{_doc(f"A list of {t} objects, indexed {indexed}; its ``add`` takes the items by keyword.", 4)}

    __slots__ = ()

{_signature(head, params, t)}
        """A new {t} at the end of the list, with the items given (the others at their defaults).

        Args:
{chr(10).join(args)}
        """
        return self._add({"name" if named else "None"}, locals())
'''


def _owner(schema: dict, type_name: str) -> str:
    """What an object of the type is: the description of the first list that holds it."""
    for t, v in schema.items():
        for name, d in v["lists"].items():
            if type_name in d["types"]:
                where = "the model" if t == "Model" else f"a {t}"
                text = d["description"][0].lower() + d["description"][1:]
                return f"An object of the list ``{name}`` of {where}: {text}"
    return ""


def generate() -> str:
    if not OUT.exists():  # the package imports the classes: a first generation starts from none
        stub = ["class ModelLists:", "class MeshList:"]
        OUT.write_text("".join(f"{c}\n    pass\n\n\n" for c in stub) + "CLASSES = {}\nLISTS = {}\n",
                       encoding="utf-8", newline="\n")
    from hydrobem_gui.objects import schema

    s = schema()
    out = ['''"""The classes of the objects of a model and of their lists, generated by
scripts/gen_model_classes.py from the schema of the engine: do not edit. Each property reads and
sets an item of the engine's object (the engine checks it); its docstring is the item's description
in the schema. ``update`` of an object and ``add`` of a list take the items by keyword, each
described in their Args; a keyword left at ``...`` is not given."""

# fmt: off
from __future__ import annotations

from collections.abc import Sequence
from typing import Literal, TypedDict

import numpy as np
from numpy.typing import ArrayLike

from .objects import BodyObject, MeshListBase, MeshObject, ModelObject, ObjectList
''']
    multi = {t for v in s.values() for d in v["lists"].values() if len(d["types"]) > 1 for t in d["types"]}
    in_named = {t for v in s.values() for d in v["lists"].values() if d["named"] or d["optional_names"]
                for t in d["types"]}  # fmt: skip
    for t, v in s.items():
        if t != "Model":
            out.append(_typed_dict(t, v, t in multi, t in in_named))
    for t, v in s.items():
        if t == "Model":
            continue
        bases = {"Mesh": "MeshObject", "Body": "BodyObject"}
        base = bases.get(t, "ModelObject")
        doc = _doc(f"{_owner(s, t)}\n\nIts items are the properties below (the schema's {t} type).", 4)
        out.append(f"\n\nclass {t}({base}):\n{doc}\n\n    __slots__ = ()\n")
        out += [_item(n, d) for n, d in v["items"].items()]
        out += [_list(n, d) for n, d in v["lists"].items()]
        out.append(_update(v))
    held = {}  # the object types held in a list of one type, and how its objects are named (_indexed)
    for v in s.values():
        for d in v["lists"].values():
            if not d["single"] and len(d["types"]) == 1:
                held[d["types"][0]] = "named" if d["named"] else "optional" if d["optional_names"] else ""
    for t, names in held.items():
        out.append(_list_class(t, s[t], names))
    out.append('\n\nclass ModelLists:\n    """The objects and lists of hb.Model, typed."""\n\n'
               "    __slots__ = ()\n")
    for n, d in s["Model"]["lists"].items():
        t = d["types"][0]
        if d["single"]:
            ann, kind = t, f"The {t} object of the model."
        elif n == "meshes":
            ann, kind = "MeshList", "A list of Mesh objects by name, with the functions that make meshes."
        else:
            ann, kind = f"{t}List", f"A list of {t} objects, by name; made by add() and insert()."
        out.append(f'''
    @property
    def {n}(self) -> {ann}:
{_doc(d["description"] + chr(10) + chr(10) + kind, 8)}
        return self._child("{n}")
''')
    names = [t for t in s if t != "Model"]
    out.append("\n\nCLASSES = {\n" + "".join(f'    "{t}": {t},\n' for t in names) + "}\n")
    out.append("\nLISTS = {\n" + "".join(f'    "{t}": {t}List,\n' for t in held) + "}\n")
    every = names + ["ModelLists"] + [f"{t}List" for t in held] + [f"{t}Items" for t in names]
    out.append("\n__all__ = [\n" + "".join(f'    "{t}",\n' for t in sorted(every)) + "]\n")
    # a signature line the types make longer than the project's 120 characters (ruff)
    long = "  # noqa: E501"
    return "\n".join(x + long if len(x) > 120 and "noqa" not in x else x for x in "".join(out).split("\n"))


def _value(d: dict) -> str:
    """The kind of an item, its shape and unit, and its default, e.g. "real [3] m = [0.0, 0.0, 0.0]"."""
    k = d["kind"]
    kind = {"array": f"{d['dtype']} array" if d["dtype"] else "array",
            "reference": f"reference to {d['target']}" if d["target"] else "reference"}.get(k, k)  # fmt: skip
    if d["shape"] and k in ("array", "terms"):
        kind += f" [{d['shape']}]"
    if d["choices"] and k == "choice":
        kind = " | ".join(f'"{c}"' for c in d["choices"])
    elif d["choices"]:
        kind += " | " + " | ".join(f'"{c}"' for c in d["choices"])
    unit = f" {d['unit']}" if d["unit"] not in ("", "1") else ""
    default = "" if d["default"] is None else f" = {d['default']}"
    return f"{kind}{unit}{default}"


def _tree(s: dict, t: str, pad: str) -> list[str]:
    """The lines of the items and lists of an object of type t, below it."""
    v = s[t]
    rows = [(n, _value(d), None) for n, d in v["items"].items()]
    for n, d in v["lists"].items():
        types = d["types"]
        if d["single"]:
            rows.append((f"{n} ({types[0]})", "", types[0]))
        else:
            key = "name" if d["named"] else "name or index" if d["optional_names"] else "index"
            rows.append((f"{n}[{key}] ({' | '.join(types)})", "", types))
    out = []
    for i, (name, value, sub) in enumerate(rows):
        last = i == len(rows) - 1
        text = pad + ("└─ " if last else "├─ ") + name
        out.append((text.ljust(44) + " " + value).rstrip() if value else text)
        deeper = pad + ("   " if last else "│  ")
        for k, u in enumerate([sub] if isinstance(sub, str) else sub or ()):
            if not isinstance(sub, str) and len(sub) > 1:
                out.append(deeper + ("└─ " if k == len(sub) - 1 else "├─ ") + f"({u})")
                out += _tree(s, u, deeper + ("   " if k == len(sub) - 1 else "│  "))
            else:
                out += _tree(s, u, deeper)
    return out


def doc_tree() -> str:
    """The tree of the inputs of inputs.md: every object of the model by its list, every item with
    its kind, shape, unit and default (as the schema)."""
    from hydrobem_gui.objects import schema

    return "\n".join(["```", "m (hb.Model)", *_tree(schema(), "Model", ""), "```"])


def doc_text() -> str:
    """inputs.md with the tree of the inputs between its markers."""
    text = DOC.read_text(encoding="utf-8")
    a, b = text.index(BEGIN) + len(BEGIN), text.index(END)
    return text[:a] + "\n" + doc_tree() + "\n" + text[b:]


def main() -> int:
    ap = argparse.ArgumentParser(description="Writes python/hydrobem_gui/_classes.py from the engine's schema.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a file is not up to date; write nothing")
    check = ap.parse_args().check
    if check and not OUT.exists():  # a check changes nothing (it would write the first stub)
        print(f"{OUT} does not exist: run scripts/gen_model_classes.py")
        return 1
    files = [(OUT, generate())]  # HydroBEM's also (DOC, doc_text()): no inputs.md here
    if check:
        # the bytes: LF line endings, as written
        stale = [p for p, text in files if p.read_bytes() != text.encode("utf-8")]
        for p in stale:
            print(f"{p} is not the output of scripts/gen_model_classes.py for this schema: run it")
        return 1 if stale else 0
    for p, text in files:
        p.write_bytes(text.encode("utf-8"))
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
