@pytest.mark.parametrize("higher_order", [False, True])
def test_the_generated_plate_fills_its_loop(higher_order):
    """The generated cover of the moonpool: its elements numbered from 1 (role free_surface_plate,
    owner 0), its normals down, its area that of the loop to rounding (the 32-gon of the low-order
    waterline, the square of the barge's), every edge of the plate's boundary on the hull's
    waterline (rule 3, conforming: no free edge, so the pressure drift is available); the waterplane
    of the body is the outer loop's (the plate's area joins the hull's)."""
    mesh = ho_hull() if higher_order else lo_hull()
    o = {"higher_order": higher_order}
    m = model(covered(mesh, modes=("heave",)), [1.0], [0.0], options=o)
    p = m.bodies["hull"].panels(role="free_surface_plate", include_reflections=False)
    assert set(p.role) == {"free_surface_plate"} and set(p.owner) == {0}
    assert sorted(p.element) == list(range(1, len(p.element) + 1))
    assert np.all(p.normals[:, 2] < -1.0 + 1e-12)
    area = _moonpool_area(8) if not higher_order else 4.0
    assert abs(4.0 * p.areas.sum() / area - 1.0) <= 1e-12, 4.0 * p.areas.sum() / area - 1.0
    # the boundary edges of the plate (those of one element only, off the symmetry planes) lie on the
    # waterline of the moonpool's wall, of radius 1 (low order: on the chords of its panels) or on the
    # square |x| = 1, |y| = 1 (higher order)
    v = p.vertices[..., :2]
    edges = {}
    for q in v:
        k = len(q) if not np.allclose(q[-1], q[-2]) else len(q) - 1
        for i in range(k):
            a, b = tuple(np.round(q[i], 12)), tuple(np.round(q[(i + 1) % k], 12))
            if a != b:
                edges[frozenset((a, b))] = edges.get(frozenset((a, b)), 0) + 1
    outer = [tuple(e) for e, c in edges.items() if c == 1]
    off_axes = [(a, b) for a, b in outer if not (abs(a[0]) < 1e-12 and abs(b[0]) < 1e-12)
                and not (abs(a[1]) < 1e-12 and abs(b[1]) < 1e-12)]  # fmt: skip
    assert off_axes
    for a, b in off_axes:
        mid = 0.5 * (np.array(a) + np.array(b))
        if higher_order:
            assert abs(max(abs(mid[0]), abs(mid[1])) - 1.0) <= 1e-12, mid
        else:
            # the midpoint of a chord of the 32-gon lies at the distance cos(pi / 32) * t from its
            # centre for a part t of the chord: on a chord when the point is on the polygon
            phi = math.atan2(mid[1], mid[0])
            sector = math.floor(phi / (math.pi / 16))
            c = math.pi / 16 * (sector + 0.5)
            assert abs(mid[0] * math.cos(c) + mid[1] * math.sin(c) - math.cos(math.pi / 32)) <= 1e-12, mid
    h = m.bodies["hull"].hydrostatics()
    outer_area = 4.0 * _moonpool_area(8) if not higher_order else 16.0
    np.testing.assert_allclose(h.waterplane_area, outer_area, rtol=1e-12)
    m.second_order.drift_pressure_integration = True
    m.first_order.motion = True
    m.bodies["hull"].update(mass=float(RHO * h.volumes[0]), center_of_gravity=[0.0, 0.0, 0.0],
                            radii_of_gyration=[1.0, 1.0, 1.0])  # fmt: skip
    m.route()  # no free plate edge: the pressure drift is available


def test_a_plate_body_over_the_loop_and_a_mirror_point():
    """A piston body over the moonpool of the trimmed hull (body names the hull), at the same place:
    its mesh is the plate the hull would generate, element for element (numbered from 1); a point
    and its mirror images across the kept planes choose the same plate; a piston at another
    position covers the same water, whole."""
    hull = covered(lo_hull())
    del hull["free_surface_plates"]
    m = model([covered(lo_hull())], [1.0], [0.0])
    own = m.bodies["hull"].panels(role="free_surface_plate", include_reflections=False)
    two = model([hull, {"name": "piston", "modes": ["heave"],
                        "free_surface_plates": [{"inside": [-0.3, 0.2], "body": "hull"}]}], [1.0], [0.0])  # fmt: skip
    p = two.bodies["piston"].panels(role="free_surface_plate", include_reflections=False)
    assert p.vertices.tobytes() == own.vertices.tobytes()
    assert list(p.element) == list(range(1, len(p.element) + 1))
    moved = {**hull, "position": [5.0, 0.0, 0.0]}
    three = model([moved, {"name": "piston", "modes": ["heave"], "position": [5.0, 1.0, 0.0], "yaw": 30.0,
                           "free_surface_plates": [{"inside": [0.0, 0.0], "body": "hull"}]}], [1.0], [0.0])  # fmt: skip
    q = three.bodies["piston"].panels(role="free_surface_plate")
    assert len(q.areas) == 4 * len(own.areas)
    np.testing.assert_allclose(q.areas.sum(), 4.0 * own.areas.sum(), rtol=1e-12)
    np.testing.assert_allclose(q.centroids[:, :2].mean(axis=0), [5.0, 0.0], atol=1e-12)


# ------------------------------------------------------------------ a small trim against a hand-made cover


def _rotation(pitch, roll):
    """The trim's rotation: the pitch about the y axis, then the roll about the x axis (inputs-bodies §1.2)."""
    a, b = math.radians(pitch), math.radians(roll)
    ry = np.array([[math.cos(a), 0.0, math.sin(a)], [0.0, 1.0, 0.0], [-math.sin(a), 0.0, math.cos(a)]])
    rx = np.array([[1.0, 0.0, 0.0], [0.0, math.cos(b), -math.sin(b)], [0.0, math.sin(b), math.cos(b)]])
    return ry @ rx


def _half_hull(n=12, freeboard=0.4):
    """Half (y >= 0) of the moonpool hull of lo_hull, its walls up to z = freeboard: (outer wall,
    moonpool wall, bottom) panels, vertices counter-clockwise from the fluid."""
    ph = np.linspace(0.0, np.pi, 2 * n + 1)
    zs = np.linspace(freeboard, -1.0, 6)
    rs = np.linspace(1.0, 2.0, n // 2 + 1)

    def p(r, k, z):
        return [r * np.cos(ph[k]), r * np.sin(ph[k]), z]

    out = []
    for i in range(2 * n):
        for j in range(len(zs) - 1):
            out.append([p(2.0, i, zs[j]), p(2.0, i, zs[j + 1]), p(2.0, i + 1, zs[j + 1]), p(2.0, i + 1, zs[j])])
            out.append([p(1.0, i, zs[j]), p(1.0, i + 1, zs[j]), p(1.0, i + 1, zs[j + 1]), p(1.0, i, zs[j + 1])])
        for j in range(n // 2):
            out.append([p(rs[j], i, -1.0), p(rs[j], i + 1, -1.0), p(rs[j + 1], i + 1, -1.0), p(rs[j + 1], i, -1.0)])
    return np.array(out)


def _clip(poly):
    """The part z <= 0 of a planar polygon (Sutherland and Hodgman 1974)."""
    out = []
    for k in range(len(poly)):
        a, b = poly[k], poly[(k + 1) % len(poly)]
        if a[2] <= 0.0:
            out.append(a)
        if (a[2] < 0.0) != (b[2] < 0.0) and a[2] != 0.0 and b[2] != 0.0:
            t = a[2] / (a[2] - b[2])
            x = a + t * (b - a)
            x[2] = 0.0
            out.append(x)
    return out


def _by_hand(mesh, elevation, pitch):
    """The hull placed (x = R xi + elevation) and cut at z = 0 in the test: its submerged panels
    (a pentagon split into a quadrilateral and a triangle) and its moonpool waterline (the cut points
    of the moonpool wall, ordered by angle about the axis of the wall)."""
    r = _rotation(pitch, 0.0)
    panels, wl = [], []
    for q in mesh:
        x = q @ r.T + [0.0, 0.0, elevation]
        c = _clip(list(x))
        uniq = []
        for y in c:
            if not uniq or np.linalg.norm(y - uniq[-1]) > 1e-12:
                uniq.append(y)
        if len(uniq) > 1 and np.linalg.norm(uniq[0] - uniq[-1]) <= 1e-12:
            uniq.pop()
        if len(uniq) < 3:
            continue
        pieces = [uniq] if len(uniq) == 4 else [uniq + [uniq[-1]]] if len(uniq) == 3 else \
            [uniq[:4], [uniq[0], uniq[3], uniq[4], uniq[4]]]  # fmt: skip
        for pc in pieces:
            pc = np.array(pc)
            if 0.5 * np.linalg.norm(np.cross(pc[2] - pc[0], pc[3] - pc[1])) > 1e-9:
                panels.append(pc)
        moonpool = np.allclose(np.hypot(q[:, 0], q[:, 1]), 1.0)
        if moonpool:
            wl.extend(y[:2] for y in uniq if abs(y[2]) <= 1e-12)
    wl = np.unique(np.round(np.array(wl), 13), axis=0)
    centre = np.array([0.5 * (wl[:, 0].min() + wl[:, 0].max()), 0.0])
    wl = wl[np.argsort(np.arctan2(wl[:, 1] - centre[1], wl[:, 0] - centre[0]))]
    return np.array(panels), wl, centre


def _fan(wl, centre):
    """The hand-made cover: a fan from the centre on y = 0 to the waterline points (half), two rings
    (a triangle and a quadrilateral per chord), normals down."""
    c = np.array([centre[0], centre[1], 0.0])
    out = []
    for a, b in zip(wl[:-1], wl[1:], strict=True):
        a3, b3 = np.array([a[0], a[1], 0.0]), np.array([b[0], b[1], 0.0])
        am, bm = 0.5 * (c + a3), 0.5 * (c + b3)
        out.append([c, bm, am, am])
        out.append([am, bm, b3, a3])
    return np.array(out)


def _against_hand(pitch):
    """(the waterplanes of the engine's trim and the hand's, the plate's area and the hand cover's,
    the largest difference of the forces) for the half moonpool hull at the pitch."""
    mesh = _half_hull()
    trimmed = {"name": "hull", "mesh": surface(mesh, symmetry="xz"), "modes": ["heave", "pitch"],
               "trim": [-0.1, pitch, 0.0], "free_surface_plates": [{"inside": CENTRE}]}  # fmt: skip
    m = model(trimmed, W, [0.0, 30.0])
    hull, wl, centre = _by_hand(mesh, -0.1, pitch)
    cover = _fan(wl, centre)
    hand = model({"name": "hull", "mesh": surface(hull, symmetry="xz"), "modes": ["heave", "pitch"],
                  "free_surface_plates": [{"mesh": surface(cover, symmetry="xz")}]}, W, [0.0, 30.0])  # fmt: skip
    areas = (m.bodies["hull"].hydrostatics().waterplane_area, hand.bodies["hull"].hydrostatics().waterplane_area)
    plate = (m.bodies["hull"].panels(role="free_surface_plate").areas.sum(),
             2.0 * np.abs(_signed_areas(cover[..., :2])).sum())  # fmt: skip
    return areas, plate, _diff(m.solve(), hand.solve())


def test_a_small_trim_against_a_hand_made_cover():
    """The half moonpool hull (12 panels a quadrant) with its walls above the water, lowered by
    0.1 m and pitched by 2 degrees: trimmed by the engine with its generated cover, against the hull
    trimmed by hand (rotated and clipped in the test) with a hand-made fan cover of its moonpool
    waterline (two rings) as an untrimmed body. The hull panels are the same and the covers fill the
    same polygon: the plate's area and the waterplane of the body to rounding, 1e-12. The forces
    differ by the discretization of the cover (refined triangles against the fan): 1.29e-2 of the
    peak found, and as much without the pitch (1.38e-2): the trim adds nothing; bounds 2e-2 and 1.5
    times the difference without the pitch."""
    found = {p: _against_hand(p) for p in (0.0, 2.0)}
    for areas, plate, _ in found.values():
        np.testing.assert_allclose(*areas, rtol=1e-12)
        np.testing.assert_allclose(*plate, rtol=1e-12)
    d0, d2 = found[0.0][2], found[2.0][2]
    assert d2 <= 2e-2 and d2 <= 1.5 * d0, (d0, d2)


# ------------------------------------------------------------------ the phase-1 identities on the trimmed moonpool


def _identities(mesh, trim, o):
    """(the cover's results, the hull and the piston body's, the Haskind error, the asymmetry of A
    and B of the two bodies, the difference of the two formulations' exciting forces)."""
    hull = {"name": "hull", "mesh": mesh, "modes": ["heave", "pitch"], "trim": trim}
    one = solve({**hull, "free_surface_plates": [{"inside": CENTRE}]}, W, [0.0, 30.0], options=o)
    piston = {"name": "lid", "modes": ["heave", "pitch"], "free_surface_plates": [{"inside": CENTRE, "body": "hull"}]}
    two = solve([hull, piston], W, [0.0, 30.0], options=o)
    X = one.excitation.diffraction
    haskind = np.abs(one.excitation.haskind - X[:, :, [2, 4]]).max() / np.abs(X).max()
    rows = [2, 4, 8, 10]
    asym = max(np.abs(x - np.swapaxes(x, 1, 2)).max() / np.abs(x).max()
               for x in (two.quantity(q)[:, rows] for q in ("added_mass", "radiation_damping")))  # fmt: skip
    other = solve({**hull, "free_surface_plates": [{"inside": CENTRE}]}, W, [0.0, 30.0],
                  options={**o, "diffraction_formulation": "scattered"})  # fmt: skip
    return one, two, haskind, asym, _rel(other.excitation.diffraction, X)


@pytest.mark.parametrize("higher_order", [False, True])
def test_the_identities_of_plates_on_the_trimmed_moonpool(higher_order):
    """The moonpool hull with its walls above the water, lowered by 0.1 m and pitched by 2 degrees
    (low order the half hull of 12 panels a quadrant, higher order the barge of 2 panels a metre):
    its cover as a plate of the hull against the hull and a piston body over its loop (the two
    moving together are the one rigid body: the sum of the blocks of their heave and pitch; the same
    plate, the same equations in another order: 1e-5), and, against the same hull without the pitch,
    the Haskind relation, the symmetry of A and B of the two bodies (the corner at the wall) and the
    two formulations, discretization errors that the pitch does not raise. Found, pitched (without):
    low order 1.2e-2 (1.6e-2), 9.9e-3 (1.1e-2), 2.4e-2 (2.0e-2), as the given cover of phase 1 (its
    Haskind error 1.1e-2 on 8 panels a quadrant, 3.4e-3 on 16, the generated cover within 1.6e-4 of
    it); higher order 2.4e-4 (4.0e-5), the formulations 2.0e-4 (8.0e-5). Bounds: low order 3e-2 and
    1.5 times the error without the pitch, higher order 1e-3."""
    o = {"higher_order": higher_order}
    mesh = ho_hull(0.4) if higher_order else surface(_half_hull(), symmetry="xz")
    found = {p: _identities(mesh, [-0.1, p, 0.0], o) for p in (0.0, 2.0)}
    one, two = found[2.0][:2]
    for q in ("added_mass", "radiation_damping"):
        a, b = one.quantity(q), two.quantity(q)
        for row, (i, j) in ((2, (2, 8)), (4, (4, 10))):
            for col, (k, m) in ((0, (0, 2)), (1, (1, 3))):
                s = b[:, i, k] + b[:, i, m] + b[:, j, k] + b[:, j, m]
                assert np.abs(a[:, row, col] - s).max() <= 1e-5 * np.abs(a).max(), (q, row, col)
    x1, x2 = one.excitation.diffraction, two.excitation.diffraction
    for i, j in ((2, 8), (4, 10)):
        assert np.abs(x1[:, :, i] - x2[:, :, i] - x2[:, :, j]).max() <= 1e-5 * np.abs(x1).max()
    for k, what in ((2, "haskind"), (3, "symmetry"), (4, "formulations")):
        e0, e2 = found[0.0][k], found[2.0][k]
        assert (e2 <= 1e-3) if higher_order else (e2 <= 3e-2 and e2 <= 1.5 * e0), (what, e0, e2)


