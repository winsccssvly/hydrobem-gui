def _half_hull_x():
    """The half hull of _half_hull turned by -90 degrees about z: the half x >= 0 (symmetry yz)."""
    h = _half_hull()
    return np.stack([h[..., 1], -h[..., 0], h[..., 2]], axis=-1)


