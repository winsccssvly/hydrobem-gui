@pytest.mark.parametrize("bodies, match", [
    # a plate mesh on a trimmed body: tilted out of z = 0
    ({**covered(lo_hull()), "free_surface_plates": [{"mesh": surface(moonpool_panels(n=8)[:1], symmetry=QUARTER)}]},
     "a free-surface plate of a trimmed body is generated from its waterline"),
    # a body of plates only cannot be trimmed
    ({"name": "p", "trim": [0.0, 1.0, 0.0], "free_surface_plates": [{"inside": CENTRE}]},
     "a body of free-surface plates only cannot be trimmed"),
    # a generated plate on a body without trim, and naming a body without trim
    ({"name": "hull", "mesh": lo_hull(), "free_surface_plates": [{"inside": CENTRE}]},
     "a generated plate covers a loop of a trimmed waterline: the body has no trim"),
    ([{"name": "hull", "mesh": lo_hull()}, {"name": "p", "free_surface_plates": [{"inside": CENTRE, "body": "hull"}]}],
     "the body 'hull' has no trimmed hull"),
    # body without inside; a trimmed body's generated plate naming another body
    ([covered(lo_hull()), {"name": "p", "free_surface_plates": [{"mesh": surface(moonpool_panels(n=8)[:1]),
                                                                   "body": "hull"}]}],
     "body names the body whose waterline loop a generated plate covers"),
    ([{**covered(lo_hull()), "name": "a"}, {**covered(lo_hull()), "name": "b", "position": [9.0, 0.0, 0.0],
                                            "free_surface_plates": [{"inside": CENTRE, "body": "a"}]}],
     "a generated plate of a trimmed body covers a loop of its own waterline"),
    # the point: in the hull's waterplane, in the open sea, on the waterline
    ({**covered(lo_hull()), "free_surface_plates": [{"inside": [1.5, 0.2]}]}, "lies in the waterplane of the hull"),
    ({**covered(lo_hull()), "free_surface_plates": [{"inside": [3.0, 0.0]}]}, "lies in the open sea"),
    ({**covered(lo_hull()), "free_surface_plates": [{"inside": [1.0, 0.0]}]}, "lies on the waterline"),
])  # fmt: skip
def test_generated_plates_are_refused_where_they_cannot_be_made(bodies, match):
    with pytest.raises(ValueError, match=match):
        model(bodies, [1.0], [0.0]).check()


def test_a_plate_over_a_disabled_body_is_refused():
    hull = {**covered(lo_hull()), "free_surface_plates": []}
    m = model([hull, {"name": "p", "free_surface_plates": [{"inside": CENTRE, "body": "hull"}]}], [1.0], [0.0])
    m.bodies["hull"].enabled = False
    with pytest.raises(ValueError, match="body: the body 'hull' is disabled"):
        m.check()
