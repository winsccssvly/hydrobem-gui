"""Free-surface plates generated on a trimmed hull (reference/inputs-bodies §2.4, theory §14;
test-plan A and B).

A plate of a trimmed body is generated by the engine: the water of z = 0 inside the waterline loop
around a point, triangulated as the low-order `waterline` interior surface (refined) or as the
interior surface of a trimmed patch mesh (higher order), its edges on the waterline. Identities of
the problem: at the trim [0, 0, 0] the generated plate is the plate given as a mesh of its elements
(the same problem, bit for bit); the plate's area is the area the loop encloses, its edges lie on
the hull's waterline (no free edge: the pressure drift is available) and its normals point down;
a small trim against the hull trimmed in the test (an independent clipping) with a hand-made cover
(a fan of its waterline, another discretization of the same plate: the waterplane to rounding, the
forces to the discretization of the plate, as without trim); on the trimmed moonpool the phase-1
identities: the cover of the hull equals the hull with a piston body over its loop moving with it
(the rigid connection), the Haskind relation, A and B symmetric, both formulations; a point on a
plane of the kept symmetry chooses the plate of a point off it (the whole loop). Both methods.
Refusals: a plate mesh on a trimmed body, a trimmed body of plates only, a point in the waterplane,
in the open sea or on the waterline, a generated plate without a trimmed hull, a plate naming a
disabled body. Meshes are procedural (tests/python/meshes.py, bodies.py)."""

import math

import numpy as np
import pytest

from bodies import flat, surface
from meshes import MOONPOOL_FACES, face_panels, moonpool_panels
from problems import model, solve, view

RHO, G = 1000.0, 9.80665
W = np.sqrt(np.array([0.5, 1.0, 2.0]) * G)
QUARTER = "xz_and_yz"
CENTRE = [0.0, 0.0]
NAMES = ("added_mass", "radiation_damping", "excitation_diffraction")


def lo_hull(n=8):
    """The quadrant of the moonpool hull (outer radius 2, moonpool 1, draft 1), its walls up to z = 0."""
    return surface(moonpool_panels(n=n), symmetry=QUARTER)


def ho_hull(freeboard=0.0):
    """The square barge 4 x 4 x 1 m with a 2 x 2 m moonpool, flat patches of 2 panels a metre
    (quadrant), its walls up to z = freeboard."""
    up = np.array([0.0, 0.0, 1.0 + freeboard])
    faces = [(o, du, up if dv == (0, 0, 1) else dv, nrm) for o, du, dv, nrm in MOONPOOL_FACES[:6]]
    q = np.array([face_panels(o, du, dv, 1, 1, nrm)[0] for o, du, dv, nrm in faces])
    nuv = [(max(1, round(np.linalg.norm(x[1] - x[0]) * 2)), max(1, round(np.linalg.norm(x[3] - x[0]) * 2))) for x in q]
    return flat(q, [(a, b, 3, 3, 3, 4) for a, b in nuv], symmetry=QUARTER)


def covered(mesh, trim=(0.0, 0.0, 0.0), modes=("heave", "pitch"), **items):
    """The trimmed hull with its plate generated over the moonpool."""
    return {"name": "hull", "mesh": mesh, "modes": list(modes), "trim": list(trim),
            "free_surface_plates": [{"inside": CENTRE}], **items}  # fmt: skip


def _rel(a, b):
    return np.abs(a - b).max() / np.abs(b).max()


def _diff(r1, r2):
    """The largest difference of A, B and the exciting force, each over its peak."""
    return max(_rel(view(r1, q), view(r2, q)) for q in NAMES)


def _same(r1, r2):
    for q in NAMES:
        assert view(r1, q).tobytes() == view(r2, q).tobytes(), q


def _signed_areas(v):
    x, y = v[..., 0], v[..., 1]
    return 0.5 * np.sum(x * np.roll(y, -1, axis=1) - np.roll(x, -1, axis=1) * y, axis=1)


def _moonpool_area(n):
    """The area of the 4 n-gon of the moonpool's waterline (radius 1): the loop the cover fills."""
    return 2.0 * n * math.sin(math.pi / (2 * n))


# ------------------------------------------------------------------ the trim [0, 0, 0]


def test_a_generated_plate_at_zero_trim_is_the_given_plate_low_order():
    """The moonpool hull trimmed by [0, 0, 0] with the plate generated at its centre, against the
    untrimmed hull with the plate given as a mesh of its own, the elements of the generated plate
    (body.trimmed_mesh with role free_surface_plate): the same problem, bit for bit."""
    m = model(covered(lo_hull()), W, [0.0])
    plate = m.bodies["hull"].trimmed_mesh("plate", role="free_surface_plate")
    assert plate.symmetry == QUARTER and np.all(np.asarray(plate.source_elements) == 0)
    given = solve({"name": "hull", "mesh": lo_hull(), "modes": ["heave", "pitch"],
                   "free_surface_plates": [{"mesh": surface(np.asarray(plate.vertices), symmetry=QUARTER)}]},
                  W, [0.0])  # fmt: skip
    _same(m.solve(), given)


def test_a_generated_plate_at_zero_trim_is_the_given_plate_higher_order():
    """The flat-patch moonpool barge trimmed by [0, 0, 0] with its generated plate, against the
    untrimmed body of the trimmed surfaces (wetted and plate) as one trimmed patch mesh of their
    source with the plate's elements as its plate: bit for bit."""
    m = model(covered(ho_hull()), W, [0.0], options={"higher_order": True})
    generated = m.solve()
    b = m.bodies["hull"]
    # (each trimmed mesh with its copy of the source holding the generated patches, the same copies)
    wet, plate = b.trimmed_mesh("tw", "wetted"), b.trimmed_mesh("tp", "free_surface_plate")
    nw, nplate = len(wet.trim_elements), len(plate.trim_elements)
    assert nplate > 0 and np.all(np.asarray(plate.trim_elements)[:, 0] > len(ho_hull()["vertices"]))
    del m.bodies["hull"]
    m.meshes.add("t", kind="trimmed_patches", source=wet.source, trim=wet.trim, symmetry=wet.symmetry,
                 trim_elements=np.concatenate([wet.trim_elements, plate.trim_elements]),
                 parameter_ranges=np.concatenate([wet.parameter_ranges, plate.parameter_ranges]),
                 discretization=np.concatenate([wet.discretization, plate.discretization]))  # fmt: skip
    gb = m.bodies.add("hull", mesh="t", ranges=[(1, nw)], modes=["heave", "pitch"])
    gb.free_surface_plates.add(mesh="t", ranges=[(nw + 1, nw + nplate)])
    _same(generated, m.solve())


